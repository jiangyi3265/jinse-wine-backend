package com.ruoyi.web.controller.business;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertThrows;

import java.lang.reflect.Field;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.Before;
import org.junit.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import com.fasterxml.jackson.databind.ObjectMapper;

public class WechatPaymentSyncTest
{
    private JdbcTemplate jdbc;
    private FakePay service;

    @Before
    public void setUp() throws Exception
    {
        JdbcDataSource source = new JdbcDataSource();
        source.setURL("jdbc:h2:mem:pay_sync_" + System.nanoTime() + ";MODE=MySQL;DB_CLOSE_DELAY=-1");
        jdbc = new JdbcTemplate(source);
        jdbc.execute("CREATE TABLE biz_order(order_id BIGINT PRIMARY KEY,member_id BIGINT,order_no VARCHAR(64),total_cent INT,status VARCHAR(16),paid_at TIMESTAMP,wechat_transaction_id VARCHAR(64))");
        jdbc.execute("CREATE TABLE biz_order_refund(refund_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,order_id BIGINT,member_id BIGINT,refund_no VARCHAR(64),amount_cent INT,reason VARCHAR(255),status VARCHAR(16),channel_status VARCHAR(32))");
        jdbc.update("INSERT INTO biz_order(order_id,member_id,order_no,total_cent,status) VALUES(1,7,'JS100',1000,'pending')");
        service = new FakePay(jdbc);
        field("enabled", true);
        field("appId", "app");
        field("merchantId", "merchant");
        field("merchantSerial", "serial");
        field("privateKeyPem", "key");
        field("apiV3Key", "12345678901234567890123456789012");
        field("notifyUrl", "https://example.com/pay");
        field("platformCertPem", "cert");
    }

    @Test
    public void checksOwnershipBeforeCallingWechat()
    {
        assertEquals(404, assertThrows(MiniBusinessException.class, () -> service.syncPaymentStatus(8, "JS100")).getCode());
        assertEquals(0, service.calls);
    }

    @Test
    public void successfulTradeIsAppliedOnce()
    {
        service.response = trade("app", "merchant", 1000, "SUCCESS");
        assertEquals("SUCCESS", service.syncPaymentStatus(7, "JS100"));
        assertEquals("SUCCESS", service.syncPaymentStatus(7, "JS100"));
        assertEquals("paid", jdbc.queryForObject("SELECT status FROM biz_order WHERE order_id=1", String.class));
        assertEquals("wx-transaction", jdbc.queryForObject("SELECT wechat_transaction_id FROM biz_order WHERE order_id=1", String.class));
    }

    @Test
    public void rejectsMismatchedTradeWithoutMarkingOrderPaid()
    {
        for (String response : new String[] {
                trade("wrong-app", "merchant", 1000, "SUCCESS"),
                trade("app", "wrong-merchant", 1000, "SUCCESS"),
                trade("app", "merchant", 999, "SUCCESS"),
                trade("app", "merchant", 1000, "SUCCESS").replace("CNY", "USD") })
        {
            service.response = response;
            assertThrows(MiniBusinessException.class, () -> service.syncPaymentStatus(7, "JS100"));
            assertEquals("pending", jdbc.queryForObject("SELECT status FROM biz_order WHERE order_id=1", String.class));
        }
    }

    @Test
    public void cancelledOrderCreatesOnlyOneAutomaticRefund()
    {
        jdbc.update("UPDATE biz_order SET status='cancelled' WHERE order_id=1");
        service.response = trade("app", "merchant", 1000, "SUCCESS");
        service.syncPaymentStatus(7, "JS100");
        service.syncPaymentStatus(7, "JS100");
        assertEquals("cancelled", jdbc.queryForObject("SELECT status FROM biz_order WHERE order_id=1", String.class));
        assertEquals(Integer.valueOf(1), jdbc.queryForObject("SELECT COUNT(*) FROM biz_order_refund WHERE order_id=1 AND channel_status='PENDING_AUTO'", Integer.class));
    }

    private String trade(String app, String merchant, int amount, String state)
    {
        return "{\"appid\":\"" + app + "\",\"mchid\":\"" + merchant + "\",\"out_trade_no\":\"JS100\","
                + "\"trade_state\":\"" + state + "\",\"transaction_id\":\"wx-transaction\","
                + "\"amount\":{\"total\":" + amount + ",\"currency\":\"CNY\"}}";
    }

    private void field(String name, Object value) throws Exception
    {
        Field field = WechatPayService.class.getDeclaredField(name);
        field.setAccessible(true);
        field.set(service, value);
    }

    private static final class FakePay extends WechatPayService
    {
        private String response;
        private int calls;

        private FakePay(JdbcTemplate jdbc) { super(jdbc, new ObjectMapper(), null); }

        @Override
        protected String request(String method, String path, String body)
        {
            calls++;
            assertEquals("GET", method);
            assertEquals("/v3/pay/transactions/out-trade-no/JS100?mchid=merchant", path);
            return response;
        }
    }
}
