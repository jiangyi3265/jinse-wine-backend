package com.ruoyi.web.controller.business;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertFalse;
import static org.junit.Assert.assertTrue;

import java.sql.Timestamp;
import java.time.Instant;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.Before;
import org.junit.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import com.fasterxml.jackson.databind.ObjectMapper;

public class PendingPaymentReconciliationJobTest
{
    private JdbcTemplate jdbc;
    private FakePay pay;
    private PendingPaymentReconciliationJob job;

    @Before
    public void setUp()
    {
        JdbcDataSource source = new JdbcDataSource();
        source.setURL("jdbc:h2:mem:pay_reconcile_" + System.nanoTime() + ";MODE=MySQL;DB_CLOSE_DELAY=-1");
        jdbc = new JdbcTemplate(source);
        jdbc.execute("CREATE TABLE biz_order(order_no VARCHAR(64) PRIMARY KEY,member_id BIGINT,status VARCHAR(16),paid_at TIMESTAMP)");
        jdbc.execute("CREATE TABLE biz_order_pay_request(pay_request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,member_id BIGINT,order_no VARCHAR(64),create_time TIMESTAMP)");
        jdbc.execute("CREATE TABLE biz_order_pay_reconcile(order_no VARCHAR(64) PRIMARY KEY,member_id BIGINT,last_trade_state VARCHAR(24),attempt_count INT,last_query_at TIMESTAMP,next_query_at TIMESTAMP,last_error VARCHAR(255))");
        pay = new FakePay(jdbc);
        job = new PendingPaymentReconciliationJob(jdbc, pay);
    }

    @Test
    public void queriesEachOrderOnceAndRetriesOnlyWhenDue()
    {
        order("JS100", "pending", true);
        paymentRequest("JS100");
        paymentRequest("JS100");
        order("JS200", "pending", false);

        job.reconcile();
        assertEquals(1, pay.calls);
        assertEquals("NOTPAY", value("SELECT last_trade_state FROM biz_order_pay_reconcile WHERE order_no='JS100'"));
        assertEquals(1, number("SELECT attempt_count FROM biz_order_pay_reconcile WHERE order_no='JS100'"));
        assertTrue(jdbc.queryForObject("SELECT next_query_at FROM biz_order_pay_reconcile WHERE order_no='JS100'", Timestamp.class).after(Timestamp.from(Instant.now())));
        job.reconcile();
        assertEquals(1, pay.calls);

        jdbc.update("UPDATE biz_order_pay_reconcile SET next_query_at=? WHERE order_no='JS100'", Timestamp.from(Instant.now().minusSeconds(1)));
        pay.state = "SUCCESS";
        job.reconcile();
        assertEquals(2, pay.calls);
        assertEquals("paid", value("SELECT status FROM biz_order WHERE order_no='JS100'"));
        assertEquals("SUCCESS", value("SELECT last_trade_state FROM biz_order_pay_reconcile WHERE order_no='JS100'"));
        assertEquals(2, number("SELECT attempt_count FROM biz_order_pay_reconcile WHERE order_no='JS100'"));
        assertEquals(null, jdbc.queryForObject("SELECT next_query_at FROM biz_order_pay_reconcile WHERE order_no='JS100'", Timestamp.class));
    }

    @Test
    public void cancelledOrderIsStillCheckedAndMismatchRequiresReview()
    {
        order("JS300", "cancelled", true);
        pay.failure = new MiniBusinessException(409, "支付金额与订单不一致");
        job.reconcile();
        assertEquals(1, pay.calls);
        assertEquals("REVIEW", value("SELECT last_trade_state FROM biz_order_pay_reconcile WHERE order_no='JS300'"));
        assertTrue(value("SELECT last_error FROM biz_order_pay_reconcile WHERE order_no='JS300'").contains("金额"));
        job.reconcile();
        assertEquals(1, pay.calls);
        assertFalse(PendingPaymentReconciliationJob.needsRetry("REVIEW"));
        pay.failure = null;
        pay.state = "SUCCESS";
        assertEquals("SUCCESS", job.reconcileOne("JS300").get("tradeState"));
        assertEquals(2, number("SELECT attempt_count FROM biz_order_pay_reconcile WHERE order_no='JS300'"));
        assertEquals("SUCCESS", value("SELECT last_trade_state FROM biz_order_pay_reconcile WHERE order_no='JS300'"));
    }

    @Test
    public void disabledMerchantSkipsQueries()
    {
        order("JS400", "pending", true);
        pay.configured = false;
        job.reconcile();
        assertEquals(0, pay.calls);
        assertEquals(0, number("SELECT COUNT(*) FROM biz_order_pay_reconcile"));
    }

    @Test
    public void temporaryFailureRetriesAndRefundStateRequiresManualReview()
    {
        order("JS500", "cancelled", true);
        pay.failure = new MiniBusinessException(502, "商户查单暂不可用");
        job.reconcile();
        assertEquals("ERROR", value("SELECT last_trade_state FROM biz_order_pay_reconcile WHERE order_no='JS500'"));
        assertTrue(jdbc.queryForObject("SELECT next_query_at FROM biz_order_pay_reconcile WHERE order_no='JS500'", Timestamp.class)
                .after(Timestamp.from(Instant.now())));
        job.reconcile();
        assertEquals(1, pay.calls);

        jdbc.update("UPDATE biz_order_pay_reconcile SET next_query_at=? WHERE order_no='JS500'",
                Timestamp.from(Instant.now().minusSeconds(1)));
        pay.failure = null;
        pay.state = "REFUND";
        job.reconcile();
        assertEquals(2, pay.calls);
        assertEquals("REFUND", value("SELECT last_trade_state FROM biz_order_pay_reconcile WHERE order_no='JS500'"));
        assertEquals(null, jdbc.queryForObject("SELECT next_query_at FROM biz_order_pay_reconcile WHERE order_no='JS500'", Timestamp.class));
        job.reconcile();
        assertEquals(2, pay.calls);
    }

    private void order(String orderNo, String status, boolean request)
    {
        jdbc.update("INSERT INTO biz_order(order_no,member_id,status) VALUES(?,7,?)", orderNo, status);
        if (request) paymentRequest(orderNo);
    }

    private void paymentRequest(String orderNo)
    {
        jdbc.update("INSERT INTO biz_order_pay_request(member_id,order_no,create_time) VALUES(7,?,?)",
                orderNo, Timestamp.from(Instant.now().minusSeconds(120)));
    }

    private int number(String sql) { return jdbc.queryForObject(sql, Integer.class); }
    private String value(String sql) { return jdbc.queryForObject(sql, String.class); }

    private static final class FakePay extends WechatPayService
    {
        private final JdbcTemplate jdbc;
        private boolean configured = true;
        private String state = "NOTPAY";
        private RuntimeException failure;
        private int calls;

        private FakePay(JdbcTemplate jdbc)
        {
            super(jdbc, new ObjectMapper(), null);
            this.jdbc = jdbc;
        }

        @Override public boolean isPayConfigured() { return configured; }

        @Override
        public String syncPaymentStatus(long memberId, String orderNo)
        {
            calls++;
            if (failure != null) throw failure;
            if ("SUCCESS".equals(state))
                jdbc.update("UPDATE biz_order SET status='paid',paid_at=NOW() WHERE order_no=? AND status='pending'", orderNo);
            return state;
        }
    }
}
